import Foundation

// macOS virtual keycodes that are modifier keys (handled via modifier byte, not as keycodes)
let macosModifierKeycodes: Set<UInt8> = [
    0x38, // Shift
    0x3C, // Right Shift
    0x3A, // Option
    0x3D, // Right Option
    0x3B, // Control
    0x3E, // Right Control
    0x37, // Command
    0x36, // Right Command
    0x39, // Caps Lock
]

func keyCodeToScanCode(_ keyCode: UInt8) -> UInt8 {
    let map: [UInt8: UInt8] = [
        // Letters - first row
        0x0C: 0x14, // Q
        0x0D: 0x1A, // W
        0x0E: 0x08, // E
        0x0F: 0x15, // R
        0x10: 0x1C, // T
        0x11: 0x17, // Y
        0x1F: 0x12, // O
        0x20: 0x18, // U
        0x22: 0x0C, // I
        0x23: 0x13, // P

        // Letters - home row
        0x00: 0x04, // A
        0x01: 0x16, // S
        0x02: 0x07, // D
        0x03: 0x09, // F
        0x05: 0x0A, // G
        0x04: 0x0B, // H
        0x26: 0x0D, // J
        0x28: 0x0E, // K
        0x25: 0x0F, // L

        // Letters - bottom row
        0x06: 0x1D, // Z
        0x07: 0x1B, // X
        0x08: 0x06, // C
        0x09: 0x19, // V
        0x0B: 0x05, // B
        0x2D: 0x11, // N
        0x2E: 0x10, // M

        // Numbers
        0x12: 0x1E, // 1
        0x13: 0x1F, // 2
        0x14: 0x20, // 3
        0x15: 0x21, // 4
        0x17: 0x22, // 5
        0x16: 0x23, // 6
        0x1A: 0x24, // 7
        0x1C: 0x25, // 8
        0x19: 0x26, // 9
        0x1D: 0x27, // 0

        // Punctuation
        0x1B: 0x2D, // -
        0x18: 0x2E, // =
        0x21: 0x2F, // [
        0x1E: 0x30, // ]
        0x2A: 0x31, // \
        0x29: 0x33, // ;
        0x27: 0x34, // '
        0x2B: 0x36, // ,
        0x2F: 0x37, // .
        0x2C: 0x38, // /
        0x32: 0x35, // `

        // Special keys
        0x24: 0x28, // Return
        0x30: 0x2B, // Tab
        0x31: 0x2C, // Space
        0x33: 0x2A, // Delete (Backspace)
        0x35: 0x29, // Escape
        0x39: 0x39, // Caps Lock

        // Arrows
        0x7B: 0x50, // Left
        0x7C: 0x4F, // Right
        0x7D: 0x51, // Down
        0x7E: 0x52, // Up

        // Function keys
        0x7A: 0x3A, // F1
        0x78: 0x3B, // F2
        0x63: 0x3C, // F3
        0x76: 0x3D, // F4
        0x60: 0x3E, // F5
        0x61: 0x3F, // F6
        0x62: 0x40, // F7
        0x64: 0x41, // F8
        0x65: 0x42, // F9
        0x6D: 0x43, // F10
        0x67: 0x44, // F11
        0x6F: 0x45, // F12
    ]

    return map[keyCode] ?? keyCode
}
